use Automattic\WooCommerce\Blocks\Payments\Integrations\AbstractPaymentMethodType;

final class Paydunya_Blocks extends AbstractPaymentMethodType
{

    private $gateway;
    // Must match the gateway ID (WC_Paydunya::$id): the data is exposed
    // to JavaScript as "paydunya_data", the key read by js/checkout.js.
    protected $name = 'paydunya';

    public function initialize()
    {
        $this->settings = get_option('woocommerce_paydunya_settings', []);
        // Reuses the instance loaded by WooCommerce instead of creating a new one.
        $gateways = WC()->payment_gateways()->payment_gateways();
        $this->gateway = isset($gateways['paydunya']) ? $gateways['paydunya'] : new WC_Paydunya();
    }

    // false if the gateway is disabled or if the currency is not the CFA franc (WC_Paydunya::is_available()).
    public function is_active()
    {
        return $this->gateway->is_available();
    }

    public function get_payment_method_script_handles()
    {

        wp_register_script(
            'paydunya-blocks-integration',
            PAYDUNYA_PLUGIN_URL . 'js/checkout.js',
            [
                'wc-blocks-registry',
                'wc-settings',
                'wp-element',
                'wp-html-entities',
                'wp-i18n',
            ],
            PAYDUNYA_VERSION,
            true
        );
        if (function_exists('wp_set_script_translations')) {
            wp_set_script_translations('paydunya-blocks-integration', 'paydunya');
        }
        return ['paydunya-blocks-integration'];
    }

    public function get_payment_method_data()
    {
        return [
            'title' => $this->gateway->title,
            // Raw text: the payment block does not interpret the HTML of the description.
            'description' => wp_strip_all_tags($this->gateway->description),
            // URL generated by WordPress: works correctly both locally (e.g., http://localhost/my-site/...)
            // and online, regardless of the plugin folder name.
            'icon' => plugins_url('assets/images/Icone.svg', __FILE__),
            'supports' => array_filter($this->gateway->supports, [$this->gateway, 'supports']),
        ];
    }
}
